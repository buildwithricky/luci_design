(CSS / "index.css").write_text(HEADER + "\n".join(
    f'@import "./{f}";' for f in ["primitives.css", "foundation.css", "semantic.css", "components.css"]) + "\n")

# ---------------------------------------------------------------- JSON (W3C DTCG format)
def nest(d, path, leaf):
    for p in path[:-1]:
        d = d.setdefault(p, {})
    d[path[-1]] = leaf

def dtcg_type(name):
    if name.startswith(("green", "neutral", "success", "warning", "danger", "info", "scrim", "color")):
        return "color"
    if name.startswith("duration"): return "duration"
    if name.startswith("easing"): return "cubicBezier"
    if name.startswith("font.family"): return "fontFamily"
    if name.startswith("font.weight"): return "fontWeight"
    if name.startswith(("z.", "opacity")): return "number"
    return "dimension"

prim = {}
for k, (v, status, note) in S.COLOR.items():
    nest(prim, k.split("."), {"$type": "color", "$value": v, "$description": note,
                              "$extensions": {"luci.status": status}})
for k, v in NONCOLOR.items():
    val = v
    if k.startswith("easing") and v.startswith("cubic"):
        val = [float(x) for x in re.findall(r"[\d.]+", v)]
    nest(prim, k.split("."), {"$type": dtcg_type(k), "$value": val})
(JSN / "primitives.tokens.json").write_text(json.dumps(prim, indent=2) + "\n")

for idx, name in ((0, "light"), (1, "dark")):
    t = {}
    for k, row in S.SEMANTIC_COLOR.items():
        nest(t, k.split("."), {"$type": "color", "$value": "{" + row[idx] + "}", "$description": row[2]})
    for k, row in S.SEMANTIC_OTHER.items():
        nest(t, k.split("."), {"$type": "shadow", "$value": row[idx], "$description": row[2]})
    (JSN / f"semantic.{name}.tokens.json").write_text(json.dumps(t, indent=2) + "\n")

roles = {"type": {}, "space": {}, "motion": {}}
for r, (size, lh, wt, ls, fam, use) in S.TYPE_ROLES.items():
    roles["type"][r] = {"$type": "typography", "$description": use, "$value": {
        "fontFamily": "{" + fam + "}", "fontSize": "{" + size + "}", "lineHeight": "{" + lh + "}",
        "fontWeight": "{" + wt + "}", "letterSpacing": "{" + ls + "}"}}
for k, (r, use) in S.SPACE_ROLES.items():
    nest(roles, k.split("."), {"$type": "dimension", "$value": "{" + r + "}", "$description": use})
for k, (d, e, use, c) in S.MOTION_ROLES.items():
    nest(roles, k.split("."), {"$type": "transition", "$description": f"{use}. {c}".strip(". "),
                               "$value": {"duration": "{" + d + "}", "timingFunction": "{" + e + "}", "delay": "0ms"}})
(JSN / "roles.tokens.json").write_text(json.dumps(roles, indent=2) + "\n")

comp = {}
for k, (r, use) in S.COMPONENT.items():
    nest(comp, k.split("."), {"$value": "{" + r + "}", "$description": use})
(JSN / "components.tokens.json").write_text(json.dumps(comp, indent=2) + "\n")

# ---------------------------------------------------------------- resolution helpers
def resolve(name, idx):
    if name in S.SEMANTIC_COLOR:
        return resolve(S.SEMANTIC_COLOR[name][idx], idx)
    if name in S.SEMANTIC_OTHER:
        return S.SEMANTIC_OTHER[name][idx]
    if name in S.COMPONENT:
        return resolve(S.COMPONENT[name][0], idx)
    if name in ALL_PRIM:
        return ALL_PRIM[name]
    raise KeyError(name)

# ---------------------------------------------------------------- inventory CSV
rows = []
for k, (v, status, note) in S.COLOR.items():
    rows.append([k, var(k), "primitive", note, v, v, "-", f"Status: {status}. Not for direct use in components"])
for k, v in NONCOLOR.items():
    rows.append([k, var(k), "primitive", "", v, v, "-", "Not for direct use in components"])
for k, (l, d, desc, use) in S.SEMANTIC_COLOR.items():
    rows.append([k, var(k), "semantic", desc, resolve(l, 0), resolve(d, 1), f"{l} / {d}", use])
for k, (l, d, desc, use) in S.SEMANTIC_OTHER.items():
    rows.append([k, var(k), "semantic", desc, l, d, "literal", use])
for r, (size, lh, wt, ls, fam, use) in S.TYPE_ROLES.items():
    rows.append([f"type.{r}", f"--type-{r}", "semantic", use, f"{ALL_PRIM[size]}/{ALL_PRIM[lh]} {ALL_PRIM[wt]}", "same", f"{size}, {lh}, {wt}, {ls}", ""])
for k, (r, use) in S.SPACE_ROLES.items():
    rows.append([k, var(k), "semantic", use, ALL_PRIM[r], "same", r, ""])
for k, (d, e, use, c) in S.MOTION_ROLES.items():
    rows.append([k, var(k) + "-duration / -easing", "semantic", use, f"{ALL_PRIM[d]} {ALL_PRIM[e]}", "same", f"{d}, {e}", c])
for k, (r, use) in S.COMPONENT.items():
    try:
        lv, dv = resolve(r, 0), resolve(r, 1)
    except KeyError:
        lv = dv = "?"
    rows.append([k, var(k), "component", use, lv, dv, r, ""])
with open(ROOT / "token-inventory.csv", "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["token", "css_variable", "layer", "description", "light_value", "dark_value", "reference", "usage"])
    w.writerows(rows)

# ---------------------------------------------------------------- contrast audit
def lum(h):
    h = h.lstrip("#"); c = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in c]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]

def ratio(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True)
    return (la + 0.05) / (lb + 0.05)

